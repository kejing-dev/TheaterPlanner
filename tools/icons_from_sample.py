#!/usr/bin/env python
"""Turns the icon set of the approved sample (sample.app.js `IC`, design package iconSet) into
VectorDrawables (24 x 24, white strokes 2 / fills; the Icon composable tints them).

    python tools/icons_from_sample.py <sample.app.js>
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
NAMES = {
    "speaker": "ic_speaker", "screen": "ic_screen", "seat": "ic_seat", "more": "ic_more", "absorber": "ic_absorber",
    "reset": "ic_reset", "minus": "ic_minus", "plus": "ic_plus", "check": "ic_check", "cross": "ic_cross",
    "warning": "ic_warning", "tv": "ic_tv", "projector": "ic_projector", "globe": "ic_globe", "trash": "ic_trash",
    "exit": "ic_exit", "unavailable": "ic_unavailable", "arrow": "ic_arrow", "hand_drag": "ic_hand_drag",
}


def attr(tag, name, default=None):
    m = re.search(r'\b%s="([^"]*)"' % re.escape(name), tag)
    return m.group(1) if m else default


def rect_path(tag):
    x, y, w, h = (float(attr(tag, k, "0")) for k in ("x", "y", "width", "height"))
    rx = float(attr(tag, "rx", "0"))
    if rx <= 0:
        return "M%g,%gh%gv%gh%gZ" % (x, y, w, h, -w)
    return ("M%g,%gh%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%gZ"
            % (x + rx, y, w - 2 * rx, rx, rx, rx, rx, h - 2 * rx, rx, rx, -rx, rx, -(w - 2 * rx), rx, rx, -rx, -rx,
               -(h - 2 * rx), rx, rx, rx, -rx))


def circle_path(tag):
    cx, cy, r = (float(attr(tag, k, "0")) for k in ("cx", "cy", "r"))
    return "M%g,%ga%g,%g 0 1 0 %g,0a%g,%g 0 1 0 %g,0Z" % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)


def vector(paths):
    body = []
    for d, fill, stroke in paths:
        a = ['android:pathData="%s"' % d]
        if fill:
            a.append('android:fillColor="#FFFFFFFF"')
        if stroke:
            a += ['android:strokeColor="#FFFFFFFF"', 'android:strokeWidth="2"', 'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
        body.append("    <path\n        " + "\n        ".join(a) + " />")
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icons_from_sample.py from the approved sample -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/src/res/android"\n'.replace("src/res", "res") +
            '    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n%s\n</vector>\n' % "\n".join(body))


def main(js):
    text = open(js, encoding="utf-8").read()
    block = re.search(r"const IC = \{(.*?)\n\};", text, re.S).group(1)
    os.makedirs(OUT, exist_ok=True)
    for m in re.finditer(r"(\w+):'([^']*)'", block):
        key, svg = m.group(1), m.group(2)
        name = NAMES.get(key)
        if not name:
            continue
        paths = []
        for el in re.finditer(r"<(path|rect|circle)\b([^>]*)/?>", svg):
            kind, tag = el.group(1), el.group(2)
            d = attr(tag, "d") if kind == "path" else rect_path(tag) if kind == "rect" else circle_path(tag)
            filled = attr(tag, "fill") == "currentColor"
            paths.append((d, filled, not filled))
        with open(os.path.join(OUT, name + ".xml"), "w", encoding="utf-8") as f:
            f.write(vector(paths))
        print(name)


if __name__ == "__main__":
    main(sys.argv[1])
